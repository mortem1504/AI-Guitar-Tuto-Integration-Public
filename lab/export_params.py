"""
Sends a measured variant to the browser.

    python export_params.py                          # the best exportable variant of results/latest.json
    python export_params.py --run 20261110-153000-notes-ab12cd3 --variant octave

Writes web/src/audio/params.lab.ts: LAB_RUN names the evaluation run, and
every overridden value carries a comment with that run's numbers. The browser
merges it over params.ts, and `evaluate.py` reads it back, so the next run
measures what was exported.

It refuses to export:
  - from a synthetic dataset (those numbers test the tools, not a guitar),
    unless --allow-synthetic, which exists for the tests;
  - lab-only variants (the median window) and the pYIN baseline, which the
    browser cannot run;
  - a run made against different params.ts / params.lab.ts than today's,
    because its numbers would describe something else.

Then run `npm run audio-check` in web/ to confirm the browser agrees.
"""

import argparse
import json
import sys
from pathlib import Path

from src.audio.web_params import PARAMS_LAB_TS, load_params, read_defaults

RESULTS = Path(__file__).resolve().parent / "results"


class ExportError(Exception):
    pass


def load_run(run_id=None, results=RESULTS):
    path = Path(results) / ("latest.json" if run_id is None else f"{run_id}/summary.json")
    if not path.exists():
        raise ExportError(f"No evaluation run at {path}. Run evaluate.py first.")
    return json.loads(path.read_text(encoding="utf-8"))


def ts_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def percent(value):
    return f"{100 * value:.1f}%"


def plan_export(run, variant, defaults, current, allow_synthetic=False):
    """The overrides to write, each with its comment. Raises ExportError when it must not export."""
    if run["synthetic"] and not allow_synthetic:
        raise ExportError(f"Run {run['run_id']} is on synthetic clips. Record a guitar (record_dataset.py) and evaluate that.")
    if variant not in run["variants"]:
        raise ExportError(f"Run {run['run_id']} has no variant {variant!r}: {', '.join(run['variants'])}")
    measured = run["variants"][variant]
    if not measured["exportable"]:
        raise ExportError(f"{variant!r} uses lab-only parameters or is the pYIN baseline: the browser cannot run it.")
    if run["params"] != current:
        changed = sorted(k for k in set(run["params"]) | set(current) if run["params"].get(k) != current.get(k))
        raise ExportError(f"params changed since run {run['run_id']} ({', '.join(changed)}). Run evaluate.py again.")

    web = run["variants"]["web"]
    final = {**current, **measured["overrides"]}
    evidence = (
        f"run {run['run_id']}, {run['clips']} clips ({', '.join(run['mic_types'])}): "
        f"accuracy {percent(measured['accuracy'])} vs {percent(web['accuracy'])}, "
        f"octave errors {measured['counts']['octave']} vs {web['counts']['octave']}"
    )
    entries = []
    for key in defaults:
        if final[key] == defaults[key]:
            continue
        if key in measured["overrides"] and measured["overrides"][key] != current[key]:
            comment = f"variant {variant!r}, {evidence}"
        else:
            comment = f"kept from lab run {run['lab_run']}" if run["lab_run"] else "kept"
        entries.append((key, final[key], comment))
    return entries, measured, web


def render(run, variant, entries):
    lines = [
        "// GENERATED by lab/export_params.py. Do not edit by hand: change the lab's",
        "// evaluation and export again. See params.ts for how the two layers combine.",
        "//",
        f"// Exported variant {variant!r} of evaluation run {run['run_id']}",
        f"// ({run['dataset']}, {run['clips']} clips). The full report is",
        f"// lab/results/{run['run_id']}/summary.md.",
    ]
    if run["synthetic"]:
        lines.append("// SYNTHETIC CLIPS: these numbers test the tools, not the detector on a guitar.")
    lines += ["", 'import type { DetectorParams } from "./params";', "", f"export const LAB_RUN: string | null = {json.dumps(run['run_id'])};", ""]
    if not entries:
        lines.append("export const LAB_OVERRIDES: Partial<DetectorParams> = {};")
    else:
        lines.append("export const LAB_OVERRIDES: Partial<DetectorParams> = {")
        for key, value, comment in entries:
            lines += [f"  // {comment}", f"  {key}: {ts_value(value)},"]
        lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Export a measured variant to web/src/audio/params.lab.ts.")
    parser.add_argument("--run", default=None, help="Run id under results/ (default: results/latest.json).")
    parser.add_argument("--variant", default=None, help="Variant to export (default: the run's best exportable).")
    parser.add_argument("--allow-synthetic", action="store_true", help="Export from synthetic clips (tests only).")
    parser.add_argument("--results", default=str(RESULTS), help=argparse.SUPPRESS)
    parser.add_argument("--out", default=str(PARAMS_LAB_TS), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    try:
        run = load_run(args.run, args.results)
        variant = args.variant or run["best_exportable"]
        entries, measured, web = plan_export(run, variant, read_defaults(), load_params(), args.allow_synthetic)
    except ExportError as error:
        print(f"Not exported: {error}")
        return 1

    if measured["accuracy"] < web["accuracy"]:
        print(f"Warning: {variant!r} ({percent(measured['accuracy'])}) is less accurate than the browser now ({percent(web['accuracy'])}).")
    Path(args.out).write_text(render(run, variant, entries), encoding="utf-8")
    print(f"Wrote {args.out}: variant {variant!r} of run {run['run_id']}, {len(entries)} override(s).")
    for key, value, _ in entries:
        print(f"  {key}: {ts_value(value)}")
    print("Now, in web/: npm run audio-check && npm run note-check && npm run build")
    return 0


if __name__ == "__main__":
    sys.exit(main())
